// мажоритарное голосование (a,b — прямые; c — уже инвертированный)
static inline int
gx5f10_maj3 (int a, int b, int c)
{
  if (a != 0 && a == b) return a;
  if (a != 0 && a == c) return a;
  if (b != 0 && b == c) return b;
  return 0;
}

// вписать значение val по адресу addr (формат конфига: пары [addr_le][val_le] с нечётного смещения)
static inline void
gx5f10_cfg_patch (uint8_t *cfg, uint16_t addr, uint16_t val)
{
  for (int i = 1; i <= GX5F10_CONFIG_LEN - 4; i += 2)
    {
      uint16_t a = cfg[i] | ((uint16_t) cfg[i + 1] << 8);
      if (a == addr)
        {
          cfg[i + 2] = val & 0xFF;
          cfg[i + 3] = (val >> 8) & 0xFF;
          return;
        }
    }
}

// собрать 224-байтный DEVICE_CONFIG под устройство по его 32-байтному OTP
static inline void
gx5f10_build_config (const uint8_t *otp, uint8_t *out)
{
  memcpy (out, gx5f10_config_base, GX5F10_CONFIG_LEN);

  int dacvalue = gx5f10_maj3 (otp[0x1a], otp[0x1f], (~otp[0x1b]) & 0xFF);
  int second   = gx5f10_maj3 (otp[0x16], otp[0x19], (~otp[0x17]) & 0xFF);

  uint16_t reg220 = (uint16_t) ((dacvalue << 4 | 8) & 0xFFFF);
  uint16_t reg5c  = (uint16_t) ((((second >> 4) + 1) * 0x10) & 0xFFFF);
  uint16_t reg5e  = reg5c
      ? (uint16_t) (((((second & 0xF) + 2) * 0x6400) / reg5c) & 0xFFFF) : 0;

  gx5f10_cfg_patch (out, 0x0220, reg220);
  gx5f10_cfg_patch (out, 0x005c, reg5c);
  gx5f10_cfg_patch (out, 0x005e, reg5e);

  // контрольная сумма: (0x5A5B - Σ int16[0:0x6f]) & 0xFFFF, LE @ 0xde
  uint32_t sum = 0;
  for (int i = 0; i < 0x6f; i++)
    sum += out[i * 2] | ((uint32_t) out[i * 2 + 1] << 8);
  uint16_t ck = (uint16_t) ((0x5A5B - sum) & 0xFFFF);
  out[0xde] = ck & 0xFF;
  out[0xdf] = (ck >> 8) & 0xFF;
}
